export const KEY_UP = 1;
export const KEY_DOWN = 2;
export const KEY_LEFT = 4;
export const KEY_RIGHT = 8;
// Action keys are edge-triggered on the server: holding them acts once.
export const KEY_INTERACT = 16;
export const KEY_RELOAD = 32;
export const KEY_HEAL = 64;
export const KEY_JUMP = 128;
export const KEY_MASK = 255;

export const PHASE_LOBBY = "lobby";
export const PHASE_DROP = "drop";
export const PHASE_PLAYING = "playing";
export const PHASE_ENDED = "ended";

export const DIFFICULTIES = ["easy", "normal", "hard"] as const;
export type Difficulty = (typeof DIFFICULTIES)[number];

// client -> server
export const MSG_INPUT = "i";
export const MSG_LATENCY = "lat";
export const MSG_SPECTATE_NEXT = "specnext";
export const MSG_SETTINGS = "settings";
// server -> client
export const MSG_KILL = "kill";
export const MSG_HIT = "hit";
export const MSG_STATS = "stats";
export const MSG_SPECTATE = "spec";
export const MSG_MATCH_END = "end";
export const MSG_NOTICE = "notice";
/** Onchain career write landed for this player (web3 mode). */
export const MSG_WEB3 = "web3";

/** Sent by the client once per fixed step. */
export interface InputMessage {
  /** Monotonic per-client sequence number, echoed back as Player.lastSeq. */
  seq: number;
  /** Bitmask of KEY_* flags. */
  keys: number;
  /** Aim angle in radians. */
  angle: number;
  fire: boolean;
  /** Weapon slot the player wants active (0 or 1). The server switches when this changes. */
  slot: number;
}

/** Broadcast to everyone for the kill feed. `killer` is "" for zone deaths. */
export interface KillMessage {
  killer: string;
  victim: string;
  weapon: string;
}

/** Sent to a shooter when one of their bullets hits a player. */
export interface HitMessage {
  x: number;
  y: number;
  damage: number;
  kill: boolean;
}

/** Sent to a player when their match is over (eliminated, or won). */
export interface StatsMessage {
  place: number;
  kills: number;
  damage: number;
  survivedSeconds: number;
  /** "" if the zone got them; also "" for the winner. */
  killer: string;
}

/** Tells a dead player whose eyes they're watching through. */
export interface SpectateMessage {
  id: string;
  name: string;
}

export interface MatchEndMessage {
  winner: string;
  winnerId: string;
  leaderboard: { name: string; kills: number }[];
  /** The match record's id (GET /matches/<id>); "" when the match had no human in it. */
  matchId: string;
}

/** From the in-game menu. Omitted fields stay as they are. */
export interface SettingsMessage {
  name?: string;
  /** The room's bot difficulty, for everyone; takes effect in the lobby. */
  difficulty?: Difficulty;
  /** Switch between playing and spectating (refused while alive in a match). */
  spectate?: boolean;
}

/**
 * Matchmaking error code: the server already runs as many games as it allows
 * (MAX_ROOMS). Colyseus sends it as the HTTP status, so it must be 200–599.
 */
export const ERR_SERVER_FULL = 503;

/** HTTP route on the game server listing the top human players. */
export const LEADERBOARD_PATH = "/leaderboard";
export const LEADERBOARD_SIZE = 50;

/** A named human player's lifetime results. Names are reserved per profile, so they're unique. */
export interface LeaderboardEntry {
  name: string;
  matches: number;
  wins: number;
  kills: number;
  damage: number;
  /** Best finishing place (1 = won). */
  bestPlace: number;
  /** ms since the epoch. */
  lastPlayed: number;
}

export interface JoinOptions {
  name?: string;
  difficulty?: Difficulty;
  /** Join only to watch. */
  spectate?: boolean;
  /**
   * The browser's secret profile token (PROFILE_TOKEN_PATTERN). Without one,
   * results aren't recorded and names aren't reserved.
   */
  profile?: string;
  /** Where the player first came from (`?ref=` on their first visit). Only stored when a profile is created. */
  ref?: string;
  /**
   * The ticket /auth/verify returned for a Spark Dream address the player
   * proved control of. The server ignores an unknown or expired ticket; with
   * a live one, the player's results are also recorded onchain against the address.
   */
  ticket?: string;
}

/** 32 random bytes, hex. Generated by the client on its first visit and kept in localStorage. */
export const PROFILE_TOKEN_PATTERN = /^[0-9a-f]{64}$/;
